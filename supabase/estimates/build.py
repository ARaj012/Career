"""Builds supabase/estimates/estimates.sql from the estimate data files.

Each record is matched by name (exams, careers, scholarships) or slug (colleges), and
upserted into public.data_estimates, so re-running after an edit updates the text.
Usage: python supabase/estimates/build.py
"""
import importlib.util
import pathlib

HERE = pathlib.Path(__file__).parent
# (data module, list name, entity, table, match column)
SOURCES = [
    ("exams", "EXAMS", "exam", "exams", "name"),
    ("careers", "CAREERS", "career", "careers", "slug"),
    ("scholarships", "SCHOLARSHIPS", "scholarship", "scholarships", "name"),
    ("colleges", "COLLEGES", "college", "colleges", "slug"),
]


def q(v):
    return "null" if v is None else "'" + str(v).replace("'", "''") + "'"


def load(name):
    path = HERE / f"{name}.py"
    if not path.exists():
        return None
    spec = importlib.util.spec_from_file_location(name, path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


import json
all_rows = []
out = ["-- Generated by supabase/estimates/build.py; edit the .py data files, not this file.", ""]
for module, attr, entity, table, col in SOURCES:
    mod = load(module)
    if not mod:
        continue
    rows = getattr(mod, attr)
    seen = set()
    for r in rows:
        key = (r[0], r[1])
        assert key not in seen, f"duplicate {entity} estimate: {key}"
        seen.add(key)
        assert r[2] in ("estimate", "secondary", "discontinued"), r
    for r in rows:
        r9 = (tuple(r) + (None,) * 9)[:9]
        all_rows.append({
            "entity": entity, "table": table, "col": col, "match": r9[0], "field": r9[1], "kind": r9[2],
            "value_text": r9[3], "basis": r9[4], "source_name": r9[5], "source_url": r9[6],
            "value_min": r9[7], "value_max": r9[8],
        })
    values = ",\n".join(
        "  (" + ", ".join(q(x) for x in (r + (None,) * (9 - len(r)))[:9]) + ")" for r in rows
    )
    out.append(f"-- {entity}: {len(rows)} entries")
    out.append(f"""insert into public.data_estimates (entity, record_id, field, kind, value_text, basis, source_name, source_url, value_min, value_max)
select '{entity}', t.id, v.field, v.kind, v.value_text, v.basis, v.source_name, v.source_url, v.value_min::numeric, v.value_max::numeric
from (values
{values}
) v(match, field, kind, value_text, basis, source_name, source_url, value_min, value_max)
join public.{table} t on t.{col} = v.match
on conflict (entity, record_id, field) do update set
  kind = excluded.kind, value_text = excluded.value_text, basis = excluded.basis,
  source_name = excluded.source_name, source_url = excluded.source_url,
  value_min = excluded.value_min, value_max = excluded.value_max, updated_at = now();
""")
(HERE / "estimates.sql").write_text("\n".join(out), encoding="utf-8")
(HERE / "estimates.json").write_text(json.dumps(all_rows, ensure_ascii=False, indent=1), encoding="utf-8")
print("wrote", HERE / "estimates.sql", "and estimates.json:", len(all_rows), "entries")
